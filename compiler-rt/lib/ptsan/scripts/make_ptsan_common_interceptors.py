FUNCTION_POINTER_WARNING = """
!!THIS SCRIPT DOES NOT DEAL WITH FUNCTION POINTERS!!"
Each function pointer will be marked with FUNCTION_POINTER.
Each function pointer will have cut off all args past the first
function pointer, since we just look for an ')'. So you need
to go add all arguments after the first function pointer*

There should be like 12 of them. Ideally leave the commented-out
FUNCTION_POINTER so we can find them later if you mess one up

Also go delete the sem_open wrapper!

Also remove the void cast from GET_RANGE in __tls_get_addr

And go stick #undef REAL
#define REAL(X) __interception::PTR_TO_REAL(X) in front of InitializeCommonInterceptors
"""
# This pattern looks for:
#   INTERCEPTOR(
#       [some-return-type],
#       [some-function-name],
#       [all text up to )]
#   ){
# capturing each in a group.
# Also handles INTERCEPTOR_WITH_SUFFIX
MATCH_INTERCEPTOR_DECL = re.compile(
    r'^\s*(INTERCEPTOR(?:_WITH_SUFFIX)?)\(\s*' # 1st group: INTERCEPTOR (and friends) call"
    r'([^,]+)\s*,\s*'             # 2nd group: return type
    r'([A-Za-z0-9_#]+)\s*,?\s*'      # 3rd group: function name
    r'(.*?)\)'                     # 4th group: the rest up to ")"
  , re.DOTALL | re.MULTILINE
)


def extract_arg_name(param: str):
  out = param.split(" ")[-1] \
            .replace("*", "") \
            .replace('[]', "") \
            .strip()
  # Not a function pointer
  if ('(' not in param):
    return out
  else:
    return f"/*FUNCTION_POINTER:*/{out.removeprefix('(')}"

known_vararg_families = ["scanf", "printf", "ioctl", "flopen", "sem_open"]
def add_args_field(m: re.Match[str]):
  [start, ret_type, func_name, params] = m.groups()

  args = [extract_arg_name(p) for p in params.split(",")]
  if "..." in args:
    assert any(f in func_name for f in known_vararg_families), func_name
    return m[0]

  if (not args or
      (len(args) == 1 and
       (args[0] == "void" or args[0].strip() == ""))):
    args_str = ''
  else:
    args_str = ', ' + ', '.join(args)


  return f"PTSAN_{start}({ret_type}, {func_name}, ({args_str}), {params})"

def main():
  with open(COMMMON_INTERCEPTORS_INC_FILE, "r") as f:
    ci_lines = f.readlines()

  # Strip out the header so we can put our own in or else this may
  # get very confusing
  while ci_lines[0].startswith("//"):
    ci_lines.pop(0)

  ci_lines = [l.replace('#include "sanitizer_', '#include "sanitizer_common/sanitizer_').
                replace("SANITIZER_INTERCEPT_IOCTL", "0 /* XXX: handle ioctl in ptsan_interceptor.cpp */")
              for l in ci_lines]

  ptsan_text = MATCH_INTERCEPTOR_DECL.sub(add_args_field, "".join(ci_lines))

  ptsan_text = AUTOGEN_HEADER + ptsan_text
  #with open(PTSAN_INTERCEPTORS_INC_FILE, "w") as f:
  #  f.write(ptsan_text)
  print(ptsan_text)

  #print(FUNCTION_POINTER_WARNING)

if __name__ == "__main__":
  main()
